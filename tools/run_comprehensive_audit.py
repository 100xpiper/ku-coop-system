print("\n=== 3. FIGURES AUDIT ===")
# parse figure lines from docx
fig_dict = {}
mode = False
for p in d.paragraphs:
    t = p.text.strip()
    if t == 'สารบัญรูปภาพ':
        mode = True
        continue
    elif t == 'สารบัญตาราง':
        mode = False
        continue
    if mode and t.startswith('ภาพที่'):
        m = re.match(r'^ภาพที่\s*(\d+).*?\.{3,}\s*(\d+)$', t)
        if m:
            fig_dict[int(m.group(1))] = m.group(2)

for i in range(1, 44):
    st = fig_dict.get(i, "?")
    p_phys, p_arab = find_exact_page(rf"ภาพที่\s*{i}\b")
