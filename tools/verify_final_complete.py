import pymupdf
import re

doc = pymupdf.open('docs/เล่มรายงานการพัฒนาระบบ_ตามเล่มตัวอย่าง.pdf')
print(f"Total pages: {len(doc)}")

def find_page(pattern):
    for i in range(12, len(doc)):
        txt = doc[i].get_text()
        if re.search(pattern, txt):
            return i - 12 + 1
    return None

