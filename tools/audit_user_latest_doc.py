import pymupdf
import re

doc = pymupdf.open('docs/รายงานพัฒนาระบบ_ล่าสุด_user.pdf')
print(f"Total pages: {len(doc)}")

# Physical page 11 is Arabic page 1
# So arabic_page = physical_page - 10
OFFSET = 10

def find_page(pat, start_idx=10):
    for i in range(start_idx, len(doc)):
        txt = doc[i].get_text()
        if re.search(pat, txt):
            return i + 1, (i + 1) - OFFSET
    return None, None

