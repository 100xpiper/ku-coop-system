import pymupdf
import re

doc = pymupdf.open('docs/เล่มรายงาน_ต้นฉบับ_GoogleDocs.pdf')

def get_page(kw):
    for idx in range(12, len(doc)):
        txt = doc[idx].get_text()
        if re.search(kw, txt):
            return idx - 12 + 1
    return None

